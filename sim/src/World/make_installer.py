# Bundles every World script into one ModuleScript, WorldInstaller.module.lua, so the whole
# World goes into Studio with one paste. Rerun after changing any World script:
#   python sim/src/World/make_installer.py
from pathlib import Path
from datetime import datetime

here = Path(__file__).parent
KINDS = {".module.lua": "ModuleScript", ".server.lua": "Script", ".client.lua": "LocalScript"}

entries = []
for f in sorted(here.glob("*.lua")):
    if f.name.startswith("WorldInstaller"):
        continue
    suffix = next(s for s in KINDS if f.name.endswith(s))
    src = f.read_text(encoding="utf-8").replace("\r\n", "\n")
    assert "]==]" not in src, f.name
    entries.append((f.name[: -len(suffix)], KINDS[suffix], src))
# modules first so SceneBuilder can require WeatherFx
entries.sort(key=lambda e: e[1] != "ModuleScript")

out = [
    "-- WorldInstaller (ModuleScript, generated by make_installer.py, do not edit by hand)",
    "-- Paste into a ModuleScript named WorldInstaller in ServerStorage, then in the Command Bar (edit mode):",
    "--   require(game.ServerStorage.WorldInstaller)()",
    "-- Replaces ServerScriptService.World and the World LocalScripts, then builds the site. Never touches Bridge.",
    "local SOURCES = {",
]
for name, kind, src in entries:
    out.append(f'\t{{ "{name}", "{kind}", [==[{src}]==] }},')
out.append("""}

return function()
	print("[WorldInstaller] version VERSION, swamp + gators + flood + hurricane")
	local sss = game:GetService("ServerScriptService")
	local sps = game:GetService("StarterPlayer"):WaitForChild("StarterPlayerScripts")
	local old = sss:FindFirstChild("World")
	if old then old:Destroy() end
	local folder = Instance.new("Folder")
	folder.Name = "World"
	folder.Parent = sss
	for _, e in ipairs(SOURCES) do
		local name, kind, src = e[1], e[2], e[3]
		local parent = kind == "LocalScript" and sps or folder
		local prev = parent:FindFirstChild(name)
		if prev then prev:Destroy() end
		local s = Instance.new(kind)
		s.Name, s.Source, s.Parent = name, src, parent
		print(("[WorldInstaller] %s %s"):format(kind, s:GetFullName()))
	end
	require(folder.SceneBuilder).build()
	print(("[WorldInstaller] done. site pieces %d, gators and egrets %d, flood water %s. Save the place (Ctrl+S)."):format(
		#workspace.Site:GetChildren(), #workspace.Site.Wildlife:GetChildren(), tostring(workspace:FindFirstChild("FloodWater") ~= nil)))
end
""")
version = datetime.now().strftime("%m%d-%H%M")
text = "\n".join(out).replace("version VERSION", "version " + version)
(here / "WorldInstaller.module.lua").write_text(text, encoding="utf-8", newline="\n")
print(f"wrote WorldInstaller.module.lua with {len(entries)} scripts, version {version}")
