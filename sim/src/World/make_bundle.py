# Bundles the World into two paste-and-Play scripts in sim/place/:
#   PlanITServer.server.lua  -> one Script in ServerScriptService. Builds the swamp when Play starts and runs everything.
#   PlanITClient.client.lua  -> one LocalScript in StarterPlayer > StarterPlayerScripts. Flash, thunder, operator panel.
# Rerun after changing any World script:  python sim/src/World/make_bundle.py
import re
from datetime import datetime
from pathlib import Path

here = Path(__file__).parent
out_dir = here.parent.parent / "place"
version = datetime.now().strftime("%m%d-%H%M")

MODULES = ["Scenarios", "WeatherFx", "Lightning", "ScenarioEngine", "SceneBuilder"]
SERVER = ["ScenarioServer", "Zone", "BeaconVisuals", "Wildlife"]
CLIENT = ["FlashClient", "ScenarioUI", "Ambience"]


def src(name, suffix):
    s = (here / f"{name}.{suffix}.lua").read_text(encoding="utf-8").replace("\r\n", "\n")
    s = re.sub(r"require\(script\.Parent\.(\w+)\)", r'req("\1")', s)
    assert "script." not in s, name
    return "\n".join("\t" + line if line else line for line in s.split("\n"))


server = [f"""-- PlanIT World, server. Generated by make_bundle.py, version {version}. Do not edit by hand.
-- Paste into ONE Script in ServerScriptService, paste PlanITClient into ONE LocalScript in
-- StarterPlayer > StarterPlayerScripts, press Play. The swamp builds itself and Storm from the west starts in Studio.
local BUNDLE_VERSION = "{version}"
local AUTO_SCENARIO = "storm_west" -- played automatically in Studio only, published servers wait for an operator

local Players = game:GetService("Players")
local RunService = game:GetService("RunService")
local ServerScriptService = game:GetService("ServerScriptService")
local StarterPlayerScripts = game:GetService("StarterPlayer"):WaitForChild("StarterPlayerScripts")
print("[PlanIT] server bundle version " .. BUNDLE_VERSION)

-- an older install of the World next to this bundle would run everything twice
local oldWorld = ServerScriptService:FindFirstChild("World")
if oldWorld then oldWorld:Destroy() warn("[PlanIT] removed the old ServerScriptService.World folder") end
for _, n in ipairs({{ "FlashClient", "ScenarioUI", "Ambience" }}) do
	local x = StarterPlayerScripts:FindFirstChild(n)
	if x then x:Destroy() warn("[PlanIT] removed old StarterPlayerScripts." .. n) end
end

local MODULES, LOADED = {{}}, {{}}
local function req(name)
	if LOADED[name] == nil then LOADED[name] = MODULES[name]() end
	return LOADED[name]
end
"""]
for m in MODULES:
    server.append(f"MODULES.{m} = function()\n{src(m, 'module')}\nend\n")
server.append("""-- build the site unless this exact version is already in the place
local site = workspace:FindFirstChild("Site")
if not site or site:GetAttribute("Version") ~= BUNDLE_VERSION then
	Players.CharacterAutoLoads = false
	local t0 = os.clock()
	req("SceneBuilder").build()
	workspace.Site:SetAttribute("Version", BUNDLE_VERSION)
	print(("[PlanIT] swamp built in %.1f s: %d site pieces, %d gators and egrets"):format(
		os.clock() - t0, #workspace.Site:GetChildren(), #workspace.Site.Wildlife:GetChildren()))
	Players.CharacterAutoLoads = true
	for _, p in ipairs(Players:GetPlayers()) do p:LoadCharacter() end
end
""")
for s in SERVER:
    server.append(f"task.spawn(function()\n{src(s, 'server')}\nend)\n")
server.append("""
if RunService:IsStudio() and AUTO_SCENARIO then
	task.delay(5, function()
		local Engine = req("ScenarioEngine")
		Engine.load(AUTO_SCENARIO)
		Engine.play()
		print("[PlanIT] Studio auto play: " .. AUTO_SCENARIO .. ". Use the panel bottom left for Hurricane, Flash flood, and the rest.")
	end)
end
""")

client = [f"""-- PlanIT World, client. Generated by make_bundle.py, version {version}. Do not edit by hand.
-- Paste into ONE LocalScript in StarterPlayer > StarterPlayerScripts. Pairs with PlanITServer.
print("[PlanIT] client bundle version {version}")
"""]
for c in CLIENT:
    client.append(f"task.spawn(function()\n{src(c, 'client')}\nend)\n")

out_dir.mkdir(exist_ok=True)
(out_dir / "PlanITServer.server.lua").write_text("\n".join(server), encoding="utf-8", newline="\n")
(out_dir / "PlanITClient.client.lua").write_text("\n".join(client), encoding="utf-8", newline="\n")
print(f"wrote sim/place/PlanITServer.server.lua and PlanITClient.client.lua, version {version}")
